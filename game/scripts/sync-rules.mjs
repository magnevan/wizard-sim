// Copies the spell grammar from the Atlas (tools/spell-atlas/rules-c.js, the source of truth
// while rules are reviewed there) into packages/rules/src/rules-c.gen.js as an ES module.
// The UMD file runs unchanged inside a function that hands it a private `module`, so it
// exports the same way under Vite, vitest and node, and touches no globals.
// Usage: npm run sync-rules   (a test fails when the copy is stale)
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
export const ATLAS = join(here, '../../tools/spell-atlas/rules-c.js');
export const OUT = join(here, '../packages/rules/src/rules-c.gen.js');

export function wrapRules(source) {
  return '// Generated by game/scripts/sync-rules.mjs from tools/spell-atlas/rules-c.js. Do not edit; run `npm run sync-rules`.\n' +
    'const SpellTreeC = (() => {\nconst module = { exports: {} };\n' +
    source.replace(/\r\n/g, '\n') +
    '\nreturn module.exports;\n})();\nexport default SpellTreeC;\n';
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(OUT, wrapRules(readFileSync(ATLAS, 'utf8')));
  console.log('rules synced:', OUT);
}
